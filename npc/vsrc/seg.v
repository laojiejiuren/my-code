module seg(
  input  [3:0] b,   
  output reg [7:0] h
);

always @(*) begin
  case(b)
    4'd0:  h = 8'b00000011;  // 0
    4'd1:  h = 8'b10011111;  // 1
    4'd2:  h = 8'b00100101;  // 2
    4'd3:  h = 8'b00001101;  // 3
    4'd4:  h = 8'b10011001;  // 4
    4'd5:  h = 8'b01001001;  // 5
    4'd6:  h = 8'b01000001;  // 6
    4'd7:  h = 8'b00011111;  // 7
    4'd8:  h = 8'b00000001;  // 8
    4'd9:  h = 8'b00001001;  // 9
    4'd10: h = 8'b00010001;  // A
    4'd11: h = 8'b11000001;  // b
    4'd12: h = 8'b01100011;  // C
    4'd13: h = 8'b10000101;  // d
    4'd14: h = 8'b01100001;  // E
    4'd15: h = 8'b01110001;  // F
    default: h = 8'b11111111; // 默认全灭
  endcase
end

endmodule